export const i18n = {
  lang: localStorage.getItem("td_lang2") || "fa", // Persian by default
  t(k) {
    return D[this.lang][k] ?? k;
  },
  set(l) {
    this.lang = l;
    localStorage.setItem("td_lang2", l);
    this.apply();
  },
  apply() {
    // updates dir/lang and all static [data-i18n] elements
    const h = document.documentElement;
    h.lang = this.lang;
    h.dir = this.lang === "fa" ? "rtl" : "ltr";
    document
      .querySelectorAll("[data-i18n]")
      .forEach((e) => (e.textContent = this.t(e.dataset.i18n)));
  },
};
export const t = (k) => i18n.t(k);
